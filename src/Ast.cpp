void UnaryExpr::typeCheck() // 补充说明：单目运算符可以出现在任何地方！！！
{
    fprintf(stderr, "UnaryExpr::typeCheck\n");
    expr->typeCheck();
    Type *type = expr->getSymbolEntry()->getType(); // 获取表达式类型

    // 如果表达式类型是void，报错
    if (type->isVoid())
    {
        fprintf(stderr, "LAB3类型检查报错:表达式类型为void\n");
        exit(EXIT_FAILURE);
    }
    else if (type->isFunc())
    {
        // 获取函数的返回值类型
        // fprintf(stderr, "type是函数类型\n");
        Type *returnType = dynamic_cast<FunctionType *>(type)->getRetType(); // 将type转换为其子类func类型，然后获取函数返回值的类型
        if (returnType->isVoid())
        {
            fprintf(stderr, "LAB3类型检查报错:函数返回值void参与单目运算\n");
            exit(EXIT_FAILURE);
        }
    }

    if (expr->CanBeCalculatedInt) // 如果expr可以计算成一个整数，用于check除数为零
    {
        CanBeCalculatedInt = true;
        switch (op)
        {
        case POS:
            CalculatedInt = expr->CalculatedInt;
            break;
        case NEG:
            CalculatedInt = -expr->CalculatedInt;
            break;
        case NOT:
            CalculatedInt = !expr->CalculatedInt;
            break;
        }

        CanBeCalculatedFloat = true;
        CalculatedFloat=CalculatedInt;
    }
    else if(expr->CanBeCalculatedFloat)
    {
        CanBeCalculatedFloat = true;
        switch (op)
        {
        case POS:
            CalculatedFloat = expr->CalculatedFloat;
            break;
        case NEG:
            CalculatedFloat = -expr->CalculatedFloat;
            break;
        case NOT:
            CalculatedFloat = !expr->CalculatedFloat;
            break;
        }
        CanBeCalculatedInt = true;
        CalculatedInt = CalculatedFloat;
    }


}

